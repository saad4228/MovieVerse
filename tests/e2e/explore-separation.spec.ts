import {test,expect} from "@playwright/test";
test("cinema movies and global discovery are separate and navigation remains responsive",async({page})=>{
 test.setTimeout(120000);
 await page.setViewportSize({width:1440,height:900});
 await page.goto("/movies",{waitUntil:"domcontentloaded"});
 await expect(page.getByRole("heading",{name:/Movies in/})).toBeVisible();
 const expected=await (await page.request.get("/api/bookable-featured?city=chennai")).json();
 await expect(page.locator(".movie-grid .movie-card")).toHaveCount(expected.featured.length);
 await expect(page.getByLabel("Movie collection")).toHaveCount(0);
 const nav=page.getByRole("navigation",{name:"Main navigation"});
 await expect(nav.getByRole("link",{name:"Watchlist",exact:true})).toBeVisible();
 await nav.getByRole("link",{name:"Explore",exact:true}).click();
 await expect(page.getByRole("heading",{name:"Explore the MovieVerse",exact:true})).toBeVisible();
 await expect(page.getByRole("heading",{name:"Hollywood Collection",exact:true})).toBeVisible();
 await expect(page.locator('.explore-collection').first().locator('.movie-card').first()).toBeVisible();
 await expect(page.locator('.explore-collection').first().locator('.card-book').first()).toContainText("Explore movie");
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:"outputs/explore-desktop.png"});
 await page.getByRole("link",{name:"Search all movies"}).click();
 await expect(page.getByLabel("Movie collection")).toBeVisible();
 await expect(page.locator(".movie-grid .movie-card").first()).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole("button",{name:"Toggle navigation"}).click();
 await expect(nav.getByRole("link",{name:"Explore",exact:true})).toBeVisible();
 await expect(nav.getByRole("link",{name:"Watchlist",exact:true})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await nav.getByRole("link",{name:"Explore",exact:true}).click();
 await expect(page.locator(".explore-hero")).toBeVisible();
 await page.screenshot({path:"outputs/explore-mobile.png"});
});
